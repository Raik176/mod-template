package de.rhm176.build.model;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Optional;
import java.util.Set;
import java.util.TreeSet;

final class ModsTomlGenerator {
    private ModsTomlGenerator() {}

    static String build(ModMetadata m, MetadataTarget t, List<String> warnings) {
        LoaderType loader = t.loader();
        boolean neoforge = loader == LoaderType.NEOFORGE;
        boolean typedDependencies = neoforge && t.minecraft().isAtLeast("1.20.5");
        StringBuilder sb = new StringBuilder();

        sb.append("# Generated by the mod build. Do not edit; configure the 'modMetadata' block instead.\n");
        sb.append("modLoader=\"javafml\"\n");
        sb.append("loaderVersion=").append(Toml.string(loaderVersionRange(m, t))).append('\n');
        sb.append("license=").append(Toml.string(m.license())).append('\n');
        if (m.issues() != null) sb.append("issueTrackerURL=").append(Toml.string(m.issues())).append('\n');

        sb.append("\n[[mods]]\n");
        sb.append("modId=").append(Toml.string(m.modId())).append('\n');
        sb.append("version=").append(Toml.string(m.version())).append('\n');
        sb.append("displayName=").append(Toml.string(m.name())).append('\n');
        if (m.updateUrl() != null) sb.append("updateJSONURL=").append(Toml.string(m.updateUrl())).append('\n');
        if (m.homepage() != null) sb.append("displayURL=").append(Toml.string(m.homepage())).append('\n');
        if (m.icon() != null) sb.append("logoFile=").append(Toml.string(m.icon())).append('\n');
        if (m.credits() != null) sb.append("credits=").append(Toml.string(m.credits())).append('\n');
        if (!m.authors().isEmpty()) {
            List<String> names = new ArrayList<>();
            for (ModMetadata.Person p : m.authors()) names.add(p.name());
            sb.append("authors=").append(Toml.string(String.join(", ", names))).append('\n');
        }
        if (!m.description().isEmpty()) sb.append("description=").append(Toml.text(m.description())).append('\n');
        if (m.environment() != ModMetadata.Environment.BOTH) {
            warnings.add(loader.displayName() + " has no mod-level environment; "
                    + "'environment' is only applied to Fabric/Quilt. Use dependency 'side' instead.");
        }

        if (neoforge) {
            for (String config : t.mixinConfigs()) {
                sb.append("\n[[mixins]]\nconfig=").append(Toml.string(config)).append('\n');
            }
        }

        Set<String> emitted = new TreeSet<>();
        String loaderId = neoforge ? "neoforge" : "forge";
        String loaderRange = neoforge ? "[" + majorMinor(t.loaderVersion()) + ",)" : "[" + major(t.loaderVersion()) + ",)";
        boolean forgeMixins = !neoforge && !t.mixinConfigs().isEmpty();
        if (forgeMixins) {
            Optional<String> minimum = ForgeMixinRules.minimumForgeVersion(t.minecraft());
            if (minimum.isPresent()) loaderRange = "[" + minimum.get() + ",)";
        }
        boolean userOverridesLoader = false;
        boolean userOverridesMinecraft = false;
        for (ModMetadata.Dependency d : m.dependencies()) {
            if (!d.appliesTo(loader)) continue;
            if (d.modId().equals(loaderId)) userOverridesLoader = true;
            if (d.modId().equals("minecraft")) userOverridesMinecraft = true;
        }
        if (!userOverridesLoader) {
            dependency(sb, m, loaderId, ModMetadata.DependencyType.REQUIRED, loaderRange,
                    ModMetadata.Side.BOTH, ModMetadata.Ordering.NONE, typedDependencies, warnings);
            emitted.add(loaderId);
        }
        if (forgeMixins && ForgeMixinRules.needsMixinBootstrap(t.minecraft())
                && m.dependencies().stream().noneMatch(d -> d.modId().equals("mixinbootstrap") && d.appliesTo(loader))) {
            dependency(sb, m, "mixinbootstrap", ModMetadata.DependencyType.REQUIRED, "[1.0.3,)",
                    ModMetadata.Side.BOTH, ModMetadata.Ordering.NONE, typedDependencies, warnings);
        }
        if (!userOverridesMinecraft) {
            dependency(sb, m, "minecraft", ModMetadata.DependencyType.REQUIRED, t.minecraftRange().toMaven(),
                    ModMetadata.Side.BOTH, ModMetadata.Ordering.NONE, typedDependencies, warnings);
        }
        for (ModMetadata.Dependency d : m.dependencies()) {
            if (!d.appliesTo(loader)) continue;
            dependency(sb, m, d.modId(), d.type(), d.range().toMaven(), d.side(), d.ordering(),
                    typedDependencies, warnings);
        }
        return sb.toString();
    }

    static String loaderVersionRange(ModMetadata m, MetadataTarget t) {
        String override = m.loaderVersionRange(t.loader());
        if (override != null) return override;
        if (t.loader() == LoaderType.FORGE) return "[" + major(t.loaderVersion()) + ",)";
        return "[1,)";
    }

    private static void dependency(
            StringBuilder sb,
            ModMetadata m,
            String modId,
            ModMetadata.DependencyType type,
            String range,
            ModMetadata.Side side,
            ModMetadata.Ordering ordering,
            boolean typed,
            List<String> warnings) {
        if (!typed && (type == ModMetadata.DependencyType.DISCOURAGED || type == ModMetadata.DependencyType.INCOMPATIBLE)) {
            warnings.add("This loader version cannot express a dependency of type " + type.name().toLowerCase(Locale.ROOT)
                    + " (on '" + modId + "'); skipped");
            return;
        }
        sb.append("\n[[dependencies.").append(m.modId()).append("]]\n");
        sb.append("modId=").append(Toml.string(modId)).append('\n');
        if (typed) {
            String value = switch (type) {
                case REQUIRED -> "required";
                case RECOMMENDED, SUGGESTED -> "optional";
                case DISCOURAGED -> "discouraged";
                case INCOMPATIBLE -> "incompatible";
            };
            sb.append("type=").append(Toml.string(value)).append('\n');
        } else {
            sb.append("mandatory=").append(type == ModMetadata.DependencyType.REQUIRED).append('\n');
        }
        sb.append("versionRange=").append(Toml.string(range)).append('\n');
        sb.append("ordering=").append(Toml.string(ordering.name())).append('\n');
        sb.append("side=").append(Toml.string(side.name())).append('\n');
    }

    private static String major(String version) {
        String head = version.split("[.\\-]")[0];
        if (!head.matches("\\d+")) throw new IllegalArgumentException("Cannot derive a loader range from '" + version + "'");
        return head;
    }

    private static String majorMinor(String version) {
        String[] parts = version.split("[.\\-]");
        if (parts.length < 2 || !parts[0].matches("\\d+") || !parts[1].matches("\\d+")) {
            throw new IllegalArgumentException("Cannot derive a loader range from '" + version + "'");
        }
        return parts[0] + "." + parts[1];
    }
}
